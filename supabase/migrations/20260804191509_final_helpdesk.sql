create or replace function public.consume_rate_limit(
  p_actor_user_id uuid,
  p_action text,
  p_max_count integer,
  p_window_seconds integer
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_window_start timestamptz;
  v_request_count integer;
begin
  if p_actor_user_id is null
     or length(trim(coalesce(p_action, ''))) = 0
     or p_max_count <= 0
     or p_window_seconds <= 0 then
    raise exception 'Parâmetros de rate limit inválidos.';
  end if;

  v_window_start := to_timestamp(
    floor(extract(epoch from clock_timestamp()) / p_window_seconds) * p_window_seconds
  );

  delete from public.request_rate_limits
  where actor_user_id = p_actor_user_id
    and action = p_action
    and window_started_at < v_window_start - interval '7 days';

  insert into public.request_rate_limits (
    actor_user_id,
    action,
    window_started_at,
    request_count,
    updated_at
  )
  values (p_actor_user_id, p_action, v_window_start, 1, now())
  on conflict (actor_user_id, action, window_started_at)
  do update set
    request_count = public.request_rate_limits.request_count + 1,
    updated_at = now()
  returning request_count into v_request_count;

  return v_request_count <= p_max_count;
end;
$$;

revoke all on function public.consume_rate_limit(uuid, text, integer, integer)
  from public, anon, authenticated;
grant execute on function public.consume_rate_limit(uuid, text, integer, integer)
  to service_role;

