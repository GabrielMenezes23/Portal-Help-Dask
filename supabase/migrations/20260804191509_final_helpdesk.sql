create or replace function app_private.ticket_is_visible(target_ticket_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.tickets as ticket
    where ticket.id = target_ticket_id
      and (
        app_private.has_support_access()
        or (
          ticket.source_active = true
          and (
            ticket.requester_user_id = (select auth.uid())
            or (
              ticket.requester_email <> ''
              and ticket.requester_email = app_private.current_user_email()
            )
          )
        )
      )
  );
$$;
revoke all on function app_private.ticket_is_visible(uuid) from public, anon;
grant execute on function app_private.ticket_is_visible(uuid) to authenticated;

create or replace function app_private.capture_ticket_status_history()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.ticket_status_history(ticket_id, previous_status, new_status, source)
    values (new.id, null, new.status_bucket, 'system');
  elsif new.status_bucket is distinct from old.status_bucket then
    insert into public.ticket_status_history(ticket_id, previous_status, new_status, source)
    values (new.id, old.status_bucket, new.status_bucket, 'system');
  end if;
  return new;
end;
$$;
