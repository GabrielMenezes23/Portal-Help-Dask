-- Link future Auth users to tickets that were already synchronized.
create or replace function app_private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (
    id,
    email,
    full_name,
    role,
    active
  )
  values (
    new.id,
    lower(coalesce(new.email, '')),
    nullif(trim(coalesce(new.raw_user_meta_data ->> 'full_name', '')), ''),
    'requester'::public.app_role,
    true
  )
  on conflict (id) do update
    set email = excluded.email,
        updated_at = now();

  update public.tickets
  set requester_user_id = new.id
  where requester_email = lower(coalesce(new.email, ''))
    and requester_email <> '';

  return new;
end;
$$;

revoke all on function app_private.handle_new_user() from public;
revoke all on function app_private.handle_new_user() from anon;
revoke all on function app_private.handle_new_user() from authenticated;

