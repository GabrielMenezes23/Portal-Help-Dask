create or replace function app_private.link_ticket_requester()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.requester_email = '' then
    new.requester_user_id = null;
    return new;
  end if;

  select profile.id
    into new.requester_user_id
  from public.profiles as profile
  where profile.active = true
    and profile.email = lower(new.requester_email)
  limit 1;

  return new;
end;
$$;

revoke all on function app_private.link_ticket_requester() from public;
