  on public.ticket_attachments
  for select
  to authenticated
  using (
    app_private.has_support_access()
    or (
      source_active = true
      and exists (
        select 1
        from public.tickets as ticket
        where ticket.id = ticket_attachments.ticket_id
          and ticket.source_active = true
          and (
            ticket.requester_user_id = (select auth.uid())
            or (
              ticket.requester_email <> ''
              and ticket.requester_email = app_private.current_user_email()
            )
          )
      )
    )
  );

