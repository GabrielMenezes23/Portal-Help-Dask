  on public.tickets
  for select
  to authenticated
  using (
    app_private.has_support_access()
    or (
      source_active = true
      and (
        requester_user_id = (select auth.uid())
        or (
          requester_email <> ''
          and requester_email = app_private.current_user_email()
        )
      )
    )
  );

