create or replace function app_private.has_support_access()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select
    (select auth.uid()) is not null
    and exists (
      select 1
      from public.profiles as profile
      where profile.id = (select auth.uid())
        and profile.active = true
        and profile.role in (
          'ti_agent'::public.app_role,
          'admin'::public.app_role
        )
    );
$$;

revoke all on function app_private.has_support_access() from public;
revoke all on function app_private.has_support_access() from anon;
grant execute on function app_private.has_support_access() to authenticated;

create or replace function app_private.current_user_email()
returns text
language sql
stable
security invoker
set search_path = ''
as $$
  select lower(coalesce((select auth.jwt()) ->> 'email', ''));
$$;

revoke all on function app_private.current_user_email() from public;
revoke all on function app_private.current_user_email() from anon;
grant execute on function app_private.current_user_email() to authenticated;

